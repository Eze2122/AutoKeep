export function translate(text: string, language: AppLanguage): string {
  return language === "en" ? (translations[text] ?? text) : text;
}
export function useAppLanguage() {
  const [language, setLanguage] = useState<AppLanguage>("es");
  useFocusEffect(useCallback(() => {
    let active = true;
    AsyncStorage.getItem("@autokeep/language").then(value => {
      if (active) setLanguage(value === "en" ? "en" : "es");
    }).catch(() => {});
    return () => { active = false; };
  }, []));
  const t = useCallback((text: string) => translate(text, language), [language]);
  return { language, t };
}
